package utilidades;

public class GestionHuertosException extends Exception {


    public GestionHuertosException() {
        super();
    }


    public GestionHuertosException(String message) {
        super(message);
    }

    public GestionHuertosException(String message, Throwable cause) {
        super(message, cause);
    }

    public GestionHuertosException(Throwable cause) {
        super(cause);
    }
}
